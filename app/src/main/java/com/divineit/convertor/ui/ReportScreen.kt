/** The verification report (Phase 4): initial comparison, correction
 *  summary, audit trail, and the final re-verification — generated by
 *  the pure VerificationReport builder, displayed as text, and savable
 *  as a .txt file. The report only ever states what the engine found. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ReportScreen(
    onBack: () -> Unit,
    viewModel: ComparisonViewModel = viewModel(
        viewModelStoreOwner = LocalContext.current as ComponentActivity
    )
) {
    val context = LocalContext.current
    val correctionsState by viewModel.correctionsState.collectAsState()
    val report = remember(correctionsState) { viewModel.reportText() }

    val saveLauncher = rememberLauncherForActivityResult(
        ActivityResultContracts.CreateDocument("text/plain")
    ) { uri ->
        if (uri != null && report != null) {
            context.contentResolver.openOutputStream(uri)?.use {
                it.write(report.toByteArray(Charsets.UTF_8))
            }
            Toast.makeText(context, "Report saved.", Toast.LENGTH_SHORT).show()
        }
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Verification Report") },
                navigationIcon = {
                    TextButton(onClick = onBack) { Text("Back") }
                }
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(16.dp)
        ) {
            if (report == null) {
                Text(
                    "No comparison has been run yet.",
                    style = MaterialTheme.typography.bodyMedium
                )
                Text(
                    "The report is generated from a comparison and its " +
                        "corrections.",
                    style = MaterialTheme.typography.bodyMedium,
                    color = Muted
                )
            } else {
                Button(
                    onClick = { saveLauncher.launch("verification-report.txt") },
                    modifier = Modifier.fillMaxWidth()
                ) { Text("Save report as .txt") }
                Text(
                    report,
                    style = MaterialTheme.typography.bodySmall,
                    modifier = Modifier
                        .fillMaxSize()
                        .verticalScroll(rememberScrollState())
                        .padding(top = 12.dp)
                )
            }
        }
    }
}
